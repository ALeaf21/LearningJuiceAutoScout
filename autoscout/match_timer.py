_DIGIT_TEMPLATES_CACHE = None


def _digit_templates(np):
    global _DIGIT_TEMPLATES_CACHE
    if _DIGIT_TEMPLATES_CACHE is None:
        _DIGIT_TEMPLATES_CACHE = {
            digit: np.array(
                [[[1.0 if char == "1" else 0.0 for char in row] for row in template] for template in templates],
                dtype=np.float32,
            )
            for digit, templates in _DIGIT_TEMPLATE_ROWS.items()
        }
    return _DIGIT_TEMPLATES_CACHE


def read_timer_seconds(cv2, np, frame) -> Optional[int]:
    panel_box = _find_timer_panel_box(cv2, frame)
    if panel_box is None:
        return None
    x, y, width, height = panel_box
    panel = frame[y:y + height, x:x + width]
    digit_mask, digit_boxes = _extract_digit_boxes(cv2, np, panel)
    if len(digit_boxes) != 3:
        return None
    digits = []
    for box in digit_boxes:
        digit = _classify_digit(np, digit_mask, box)
        if digit is None:
            return None
        digits.append(digit)
    minutes = int(digits[0])
    seconds = int(digits[1] + digits[2])
    if seconds >= 60:
        return None
    return minutes * 60 + seconds


def scan_match_bounds(
    video_path: str,
    cv2,
    np,
    progress_callback: Optional[Callable[[int, int], None]] = None,
) -> Dict[str, object]:
    cap = cv2.VideoCapture(video_path)
    if not cap.isOpened():
        return {"ok": False, "readings": [], "start_frame": None, "stop_frame": None}

    fps = cap.get(cv2.CAP_PROP_FPS) or 30.0
    total_frames = int(cap.get(cv2.CAP_PROP_FRAME_COUNT))
    sample_step = max(1, int(round(fps / 2.0)))
    sample_total = max(1, total_frames // sample_step)
    sample_index = 0
    frame_index = 0
    readings = []

    while True:
        grabbed = cap.grab()
        if not grabbed:
            break
        if frame_index % sample_step == 0:
            ok, frame = cap.retrieve()
            if ok:
                seconds = read_timer_seconds(cv2, np, frame)
                readings.append({
                    "frame": frame_index,
                    "seconds": seconds,
                })
            sample_index += 1
            if progress_callback:
                progress_callback(sample_index, sample_total)
        frame_index += 1

    cap.release()

    smoothed = _smooth_seconds(readings)
    start_frame = _estimate_start_frame(smoothed, fps)
    stop_frame = _estimate_stop_frame(smoothed, fps, total_frames)
    return {
        "ok": bool(any(item["seconds"] is not None for item in smoothed)),
        "readings": smoothed,
        "start_frame": start_frame,
        "stop_frame": stop_frame,
        "fps": fps,
        "total_frames": total_frames,
    }


def _find_timer_panel_box(cv2, frame) -> Optional[tuple]:
    hsv = cv2.cvtColor(frame, cv2.COLOR_BGR2HSV)
    mask = cv2.inRange(hsv, (0, 0, 170), (180, 80, 255))
    contours, _ = cv2.findContours(mask, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)
    frame_height, frame_width = frame.shape[:2]
    best_box = None
    best_area = 0
    for contour in contours:
        x, y, width, height = cv2.boundingRect(contour)
        area = width * height
        if area <= best_area or area < 1800:
            continue
        if y <= frame_height * 0.7:
            continue
        if x >= frame_width * 0.7 or (x + width) <= frame_width * 0.3:
            continue
        best_area = area
        best_box = (x, y, width, height)
    return best_box


def _extract_digit_boxes(cv2, np, panel) -> tuple:
    gray = cv2.cvtColor(panel, cv2.COLOR_BGR2GRAY)
    y0 = int(panel.shape[0] * 0.28)
    y1 = int(panel.shape[0] * 0.77)
    digit_band = gray[y0:y1, :]
    _, digit_mask = cv2.threshold(digit_band, 170, 255, cv2.THRESH_BINARY_INV)
    digit_mask = cv2.morphologyEx(
        digit_mask,
        cv2.MORPH_OPEN,
        np.ones((2, 2), dtype=np.uint8),
    )
    contours, _ = cv2.findContours(digit_mask, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)
    digit_boxes = []
    for contour in contours:
        x, y, width, height = cv2.boundingRect(contour)
        if width * height < 40:
            continue
        if height < digit_band.shape[0] * 0.35:
            continue
        digit_boxes.append((x, y, width, height))
    digit_boxes.sort(key=lambda item: item[0])
    return digit_mask, digit_boxes


def _classify_digit(np, digit_mask, box) -> Optional[str]:
    x, y, width, height = box
    glyph = digit_mask[y:y + height, x:x + width]
    glyph = np.pad(glyph, ((2, 2), (2, 2)), mode="constant", constant_values=0)
    glyph = np.asarray(glyph > 64, dtype=np.float32)
    glyph = glyph.astype(np.uint8) * 255
    glyph = _resize_binary_glyph(np, glyph, 16, 24)
    glyph = np.asarray(glyph > 64, dtype=np.float32)

    best_digit = None
    best_score = None
    for digit, templates in _digit_templates(np).items():
        score = float(np.min(np.mean(np.abs(templates - glyph), axis=(1, 2))))
        if best_score is None or score < best_score:
            best_digit = digit
            best_score = score

    if best_score is None or best_score > 0.32:
        return None
    return best_digit


def _resize_binary_glyph(np, glyph, width: int, height: int):
    import cv2

    resized = cv2.resize(glyph, (width, height), interpolation=cv2.INTER_AREA)
    return np.asarray(resized, dtype=np.uint8)


def _smooth_seconds(readings: List[Dict[str, object]]) -> List[Dict[str, object]]:
    smoothed = []
    for index, item in enumerate(readings):
        seconds = item["seconds"]
        if seconds is None:
            smoothed.append(dict(item))
            continue
        window = []
        for neighbor_index in range(max(0, index - 1), min(len(readings), index + 2)):
            neighbor_seconds = readings[neighbor_index]["seconds"]
            if neighbor_seconds is not None:
                window.append(int(neighbor_seconds))
        if window:
            seconds = sorted(window)[len(window) // 2]
        smoothed.append({
            "frame": int(item["frame"]),
            "seconds": int(seconds),
        })
    return smoothed


def _estimate_start_frame(readings: List[Dict[str, object]], fps: float) -> Optional[int]:
    valid = [item for item in readings if item["seconds"] is not None]
    if not valid:
        return None

    anchor_index = 0
    for index, item in enumerate(valid):
        if int(item["seconds"]) >= 145:
            anchor_index = index
            break
    anchored = valid[anchor_index:]

    first_live = None
    last_frozen_230 = None
    for item in anchored:
        seconds = int(item["seconds"])
        if seconds == 150:
            last_frozen_230 = item
            continue
        if 120 <= seconds < 150:
            first_live = item
            break

    if first_live is not None:
        live_seconds = int(first_live["seconds"])
        start_frame = int(first_live["frame"] - max(0, 150 - live_seconds) * fps)
        if last_frozen_230 is not None and int(last_frozen_230["frame"]) <= int(first_live["frame"]):
            transition_start = int(first_live["frame"] - max(1, 150 - live_seconds) * fps)
            start_frame = min(start_frame, transition_start)
        return max(0, start_frame)

    earliest = anchored[0] if anchored else valid[0]
    return max(0, int(earliest["frame"]))


def _estimate_stop_frame(readings: List[Dict[str, object]], fps: float, total_frames: int) -> Optional[int]:
    valid = [item for item in readings if item["seconds"] is not None]
    if not valid:
        return None

    zero_hits = []
    previous_seconds = None
    for item in valid:
        seconds = int(item["seconds"])
        if previous_seconds is not None and seconds >= previous_seconds + 20:
            previous_seconds = seconds
            continue
        if seconds <= 1 and previous_seconds is not None and previous_seconds > 1:
            zero_hits.append(item)
        previous_seconds = seconds

    if zero_hits:
        target = zero_hits[2] if len(zero_hits) >= 3 else zero_hits[-1]
        return min(total_frames - 1, int(target["frame"] + fps))

    low_readings = [item for item in valid if int(item["seconds"]) <= 2]
    if low_readings:
        return min(total_frames - 1, int(low_readings[-1]["frame"] + fps))

    return None
